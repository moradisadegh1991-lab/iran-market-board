export const lessonById = (id: string) => LESSONS.find((l) => l.id === id) ?? null;
export const questionById = (id: string) => {
  for (const l of LESSONS) {
    const q = l.quiz.find((x) => x.id === id);
    if (q) return { lesson: l, q };
  }
  return null;
};

/**
 * What «گوش بده» reads for one step of a lesson: its title, its text without the bold marks, and on the last step the
 * key point. The voice layer (lib/voice-io.ts) turns digits into words and the written style into the spoken one.
 */
export function stepSpeech(lesson: Lesson, i: number): string {
  const st = lesson.steps[i];
  if (!st) return '';
  const parts = [`${st.title}.`, ...st.body.map((b) => b.replace(/\*\*/g, ''))];
  if (i === lesson.steps.length - 1) parts.push(`نکته کلیدی: ${lesson.takeaway}`);
  return parts.join(' ');
}
